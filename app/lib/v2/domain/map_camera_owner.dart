// lib/v2/domain/map_camera_owner.dart
//
// 지도 카메라를 지금 **누가 쥐고 있나** — 앱인가, 사용자의 손가락인가 (이슈 #769).
//
// ## 왜 필요한가
//
// 지도를 열면 앱이 카메라를 스스로 옮기는 자리가 셋이다 — 현위치가 도착했을 때, 고른 동네를
// 읽었을 때, 지도가 준비됐을 때. 셋 다 **기다린 뒤에** 옮기는데, 그 기다림이 길다(현위치는
// 상한이 25초다). 그 사이 사용자는 이미 지도를 확대해 놓았고, 늦게 도착한 값이 그것을 덮는다.
//
// 실제로 그랬다(2026-09-21 실측): 을지로입구까지 확대해 둔 지도가 위치가 도착한 2초 뒤 성수
// 일대로 되돌아갔고, 장소들이 다시 숫자 뭉치로 접혀 **개별 장소를 누를 수 없었다.**
//
// ## 두 가지를 따로 묻는다
//
// 이 객체는 서로 다른 질문 둘에 답한다. 하나로 뭉뚱그리면 둘 중 하나가 틀린 답을 받는다.
//
//  1. [mayAutoMove] — **사용자가 이 화면에서 한 번이라도 카메라를 쥔 적이 있나.**
//     한 번 쥐면 계속 사용자 것이다. 늦게 도착하는 값(현위치·고른 동네)이 덮는 것을 막는다.
//  2. [lastMoveByUser] — **방금 그 이동이 사용자의 손가락이었나.** 끈적이지 않는다.
//     카메라가 멈췄을 때 "이 지역에서 다시 찾기" 를 물을지 가른다 — 앱이 코스에 맞춰 옮긴
//     것까지 "사용자가 지도를 옮겼다" 로 읽으면 앱이 자기가 그린 선을 스스로 지운다
//     (2026-09-21 검토에서 잡았다).
//
// ## 부탁은 여기 안 담는다
//
// 사용자가 **앱에게 옮겨 달라고** 한 것(갈래 칩 · "이 지역에서 다시 찾기")은 이 객체의 상태를
// 건드리지 않는다. 그 허락은 호출에 실어 보낸다(`_load(byRequest: true)`).
//
// 예전에는 `appWasAsked()` 로 여기서 되돌렸는데 **그것이 구멍이었다.** 되돌리는 순간 그
// 한 번의 부탁만이 아니라 **아직 도착하지 않은 자동 이동까지** 문이 열린다. 칩을 누르고
// 가만히 있으면 몇 초 뒤 도착한 현위치가 확대해 둔 지도를 다시 뺏어 갔다 — #769 가 한 단계
// 뒤에서 그대로 살아 있었다(2026-09-21 검토). 허락은 "누가 무엇을 부탁했나" 를 아는 자리에서
// 그 호출에만 주어야 한다.
//
// 플러그인이 이유를 알려 준다(`NCameraUpdateReason`). 여기서는 그것을 `bool` 하나로 받는다 —
// 규칙을 지도 없이 재기 위해서다.
library;

class MapCameraOwner {
  bool _userMoved = false;
  bool _lastByUser = false;

  /// 사용자가 이 화면에서 카메라를 쥔 적이 있나. 한 번 쥐면 계속 참이다.
  bool get userMoved => _userMoved;

  /// 앱이 스스로 옮겨도 되나 — 늦게 도착한 값이 사용자의 확대를 덮지 않게 한다.
  bool get mayAutoMove => !_userMoved;

  /// **방금** 그 이동이 사용자의 손가락이었나. 끈적이지 않는다.
  ///
  /// 앱이 옮긴 뒤에는 거짓이다. 카메라가 멈춘 것을 "사용자가 여기로 왔다" 로 읽어 다시
  /// 조회하면, 앱이 방금 그린 코스 선을 그 조회가 지운다.
  bool get lastMoveByUser => _lastByUser;

  /// 카메라가 움직였다. [byUser] 면 사용자의 손가락이다(제스처·줌 컨트롤).
  ///
  /// 앱이 옮긴 것(`developer`)이나 위치 추적·여백 변경으로 움직인 것은 **주인을 바꾸지 않는다** —
  /// 그것까지 사용자 것으로 치면 앱의 첫 자리잡기 한 번에 영영 잠긴다.
  void moved({required bool byUser}) {
    _lastByUser = byUser;
    if (byUser) _userMoved = true;
  }
}
