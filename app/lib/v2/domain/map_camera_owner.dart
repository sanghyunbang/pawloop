// lib/v2/domain/map_camera_owner.dart
//
// 지도 카메라를 지금 **누가 쥐고 있나** — 앱인가, 사용자의 손가락인가 (이슈 #769).
//
// ## 왜 필요한가
//
// 지도를 열면 앱이 카메라를 스스로 옮기는 자리가 셋이다 — 현위치가 도착했을 때, 고른 동네를
// 읽었을 때, 지도가 준비됐을 때. 셋 다 **기다린 뒤에** 옮기는데, 그 기다림이 길다(현위치는
// 상한이 25초다). 그 사이 사용자는 이미 지도를 확대해 놓았고, 늦게 도착한 값이 그것을 덮는다.
//
// 실제로 그랬다(2026-09-21 실측): 을지로입구까지 확대해 둔 지도가 위치가 도착한 2초 뒤 성수
// 일대로 되돌아갔고, 장소들이 다시 숫자 뭉치로 접혀 **개별 장소를 누를 수 없었다.**
//
// ## 규칙 셋
//
//  1. 사용자가 손으로 옮겼으면(제스처·줌 컨트롤) 그때부터 카메라는 **사용자 것**이다.
//  2. 앱이 스스로 옮기는 것([mayAutoMove])은 사용자 것이 아닐 때만.
//  3. 사용자가 **앱에게 옮겨 달라고** 했으면(갈래 칩 · "이 지역에서 다시 찾기") 다시 앱 차례다
//     ([appWasAsked]) — 그것까지 막으면 칩을 눌러도 지도가 안 따라오는 다른 고장이 된다.
//
// 플러그인이 이유를 알려 준다(`NCameraUpdateReason`). 여기서는 그것을 `bool` 하나로 받는다 —
// 규칙을 지도 없이 재기 위해서다.
library;

class MapCameraOwner {
  bool _userMoved = false;

  /// 지금 카메라가 사용자 것인가.
  bool get userMoved => _userMoved;

  /// 앱이 스스로 옮겨도 되나.
  bool get mayAutoMove => !_userMoved;

  /// 카메라가 움직였다. [byUser] 면 사용자의 손가락이다(제스처·줌 컨트롤).
  ///
  /// 앱이 옮긴 것(`developer`)이나 위치 추적·여백 변경으로 움직인 것은 **주인을 바꾸지 않는다** —
  /// 그것까지 사용자 것으로 치면 앱의 첫 자리잡기 한 번에 영영 잠긴다.
  void moved({required bool byUser}) {
    if (byUser) _userMoved = true;
  }

  /// 사용자가 앱에게 옮겨 달라고 했다 — 다시 앱 차례다.
  void appWasAsked() {
    _userMoved = false;
  }
}
