// 두 법정 문서가 **꼭 있어야 하는 칸**을 들고 있는가 — 이슈 #682.
//
// ## 무엇을 재나
//
// 개인정보처리방침의 **개인정보 보호책임자** 블록 하나다. 「개인정보 보호법」 제30조제1항제6호가
// 보호책임자의 **성명**(또는 개인정보 보호업무 및 관련 고충사항을 처리하는 부서의 명칭)과
// **연락처**를 처리방침에 적도록 한다. 이 블록이 통째로 빠지면 제30조 위반(1천만원 이하)과
// 제31조 위반(3천만원 이하)이 동시에 걸린다 — 이 검사가 막는 것이 그것이다.
//
// ## 전화번호는 안 잰다 — 법이 요구하지 않는다
//
// 처음에는 전화번호도 필수로 재고 있었다. 사업자를 전제로 조문을 읽은 결과였고, **틀렸다.**
//
// 제30조제1항제6호의 문구는 "…부서의 명칭과 **전화번호 등 연락처**" 다. 전화번호를 특정하지
// 않는다. 개인정보보호위원회의 「개인정보 처리방침 작성지침」(2025.4.) 65쪽도 같은 항목을
// "연락처(전화번호, **전자우편 주소** 등)" 로 풀어 쓴다. 입법자가 전화번호를 꼭 받아야 할 때는
// 그렇게 못박는다 — 국내대리인 조항(제31조의2제4항)은 "성명·주소·**전화번호** 및 전자우편 주소"
// 라고 적고 누락 시 과태료까지 둔다. 제30조제1항제6호는 그렇게 쓰이지 않았다.
//
// 요건의 본질은 전화기가 아니라 **실제로 고충처리가 되는 연락처**다(표준 개인정보 보호지침
// 제22조제2항). 읽히는 이메일 하나면 조문을 만족한다.
//
// ## 위치기반서비스 이용약관은 왜 안 재나
//
// 「위치정보의 보호 및 이용 등에 관한 법률」 제19조의 약관 명시 의무는 **위치기반서비스사업자**
// 에게만 붙는다(제12조제1항제2호가 "신고한 자" 로 정의한다). 포루프는 제9조제1항 괄호의
// **"개인위치정보를 대상으로 하지 아니하는 위치기반서비스사업"** 이라 신고 대상이 아니고,
// 신고 면제자에게 준용되는 조문을 열거한 제38조의3 목록에 제12조·제18조·제19조가 **없다.**
//
// 그래서 그 약관의 칸을 법으로 강제하지 않는다. 다만 문서가 **왜 신고 대상이 아닌지를 스스로
// 말하는지**는 잰다 — 그 한 문단이 없으면 다음 사람이 "약관이 부실하다" 고 읽고 없는 의무를
// 다시 만들어 넣는다. 실제로 그렇게 한 번 갔다 왔다.
//
// ## 왜 "값" 이 아니라 "칸" 을 재는가
//
// 성명은 운영자가 정하는 값이라 지금 저장소에 없다. 없는 값을 지어 넣으면 심사자와 이용자에게
// **거짓말이 된다** — 연락이 안 닿는 정보가 적힌 처리방침은 아예 없는 것보다 나쁘다. 그래서
// 자리를 만들고 비어 있다는 것을 문서가 스스로 말하게 했다.
//
// 값이 채워져도 이 검사는 초록이다. **값이 들어오는 날 고칠 것은 이 파일이 아니라 문서의 버전이다.**

import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// 값이 아직 없는 칸에 적는 **단 하나의** 표시.
///
/// 두 문서가 같은 말을 써야 출시 전에 `grep` 한 번으로 남은 칸을 전부 찾는다.
const String kBlank = '(아직 비어 있습니다)';

File get _privacy => File('assets/terms/privacy_ko.md');
File get _location => File('assets/terms/location_ko.md');

/// 문단을 **한 줄로 눕힌** 사본. 산문을 찾을 때 쓴다.
///
/// 마크다운 문서는 한 문장이 여러 줄에 걸친다. `contains('신고 의무')` 가 실제 문서의
/// `신고\n의무` 를 못 찾아 빨간불이 났다 — 문서를 고칠 일이 아니라 검사를 고칠 일이다.
/// 칸(`- 라벨: 값`)을 재는 [_field] 는 반대로 줄 단위여야 하므로 그쪽은 안 눕힌다.
String _flat(File f) => _read(f).replaceAll(RegExp(r'\s+'), ' ');

String _read(File f) {
  if (!f.existsSync()) {
    fail('${f.path} 가 없습니다. 테스트를 app/ 에서 돌리고 있는지 확인하세요.');
  }
  return f.readAsStringSync();
}

/// `- 라벨: 값` 줄에서 값만 꺼낸다. 그런 줄이 없으면 `null` — 칸 자체가 없다는 뜻이다.
///
/// 공백을 `\s` 가 아니라 **`[ \t]` 로** 잡는다. `\s` 는 줄바꿈도 먹어서 `- 성명:` 처럼 값이
/// 빈 줄이면 다음 줄의 값을 끌어다 붙인다 — 그러면 "빈 칸" 을 재는 검사가 늘 초록이다.
/// 실제로 그랬다: 값을 지우는 변형을 넣었는데 통과했다.
String? _field(String source, String label) {
  final match =
      RegExp('^-[ \\t]*$label:[ \\t]*(.*)\$', multiLine: true).firstMatch(source);
  return match?.group(1)?.trim();
}

/// 한 문서의 칸들을 한꺼번에 잰다 — 있는가, 그리고 비어 있지 않은가.
void _expectFields(File file, List<String> labels, {required String why}) {
  final source = _read(file);
  for (final label in labels) {
    final value = _field(source, label);
    expect(value, isNotNull, reason: '''
${file.path} 에 "- $label:" 줄이 없습니다. $why''');
    expect(value, isNotEmpty, reason: '''
${file.path} 의 "- $label:" 이 빈 줄입니다. 값이 아직 없으면 $kBlank 라고 적어
**비어 있다는 사실을 문서가 말하게** 해야 합니다 — 빈 줄은 문서가 깨진 것으로 읽힙니다.''');
  }
}

void main() {
  group('개인정보처리방침 — 개인정보 보호법 제30조제1항제6호', () {
    test('보호책임자의 담당·이메일 칸이 있고 비어 있지 않다', () {
      _expectFields(
        _privacy,
        const ['담당', '이메일'],
        why: '개인정보 보호법 제30조제1항제6호가 이름을 대어 요구하는 칸이라, '
            '지우면 법정 기재사항이 다시 빠집니다. 블록이 통째로 없으면 제30조(1천만원 이하)와 '
            '제31조(3천만원 이하)가 동시에 걸립니다.',
      );
    });

    test('조문의 어느 갈래를 쓰는지 문서가 밝힌다', () {
      // 제30조제1항제6호는 "성명 **또는** 부서의 명칭" 두 갈래다. 개인이 만든 앱에는
      // 조직의 부서가 없어서 뒤쪽 갈래를 쓰는데, **그 사실을 문서가 말하지 않으면**
      // 읽는 사람은 성명 자리에 사람 이름이 아닌 것이 적힌 것으로만 본다.
      //
      // 이 갈래 선택은 확신이 높은 자리가 아니다 — 개인에게 "부서" 를 인정한 유권해석을
      // 못 찾았다. 그래서 근거를 문서 안에 남겨 두고, 문제되면 성명으로 바꾼다.
      final source = _flat(_privacy);
      expect(source, contains('부서의 명칭'), reason: '''
어느 갈래를 쓰는지 문서가 안 밝히면, 나중에 이 칸을 보는 사람이 근거를 처음부터 다시 찾습니다.''');
      expect(source, contains('제30조제1항제6호'));
    });

    test('담당 이름이 자리표시가 아니다', () {
      expect(_field(_read(_privacy), '담당'), isNot(kBlank));
    });

    test('이메일은 자리표시가 아니라 **진짜 값**이다 — 연락이 닿아야 조문을 만족한다', () {
      // 성명은 비어 있어도 되지만 연락처는 아니다. 표준 개인정보 보호지침 제22조제2항이
      // "고충처리 및 상담을 **실제로 처리할 수 있는** 연락처" 를 요구한다.
      final email = _field(_read(_privacy), '이메일');
      expect(email, isNotNull);
      expect(email, isNot(kBlank), reason: '''
보호책임자의 이메일이 비어 있으면 이 문서는 연락할 방법을 말하지 않는 것입니다.
성명은 나중에 채워도 되지만 연락처는 지금 있어야 합니다.''');
      expect(email, contains('@'));
    });

    test('전화번호를 강제하지 않는다 — "전화번호 등 연락처" 이기 때문이다', () {
      // 이 검사는 전화번호 줄이 **없어도 통과해야 한다.** 예전에 사업자 기준으로
      // 전화번호를 필수로 재다가 개인 개발자에게 없는 의무를 지웠다.
      //
      // 있어도 통과한다 — 나중에 번호를 적기로 하면 그때는 그냥 칸이 하나 느는 것이다.
      final phone = _field(_read(_privacy), '전화번호');
      if (phone != null) {
        expect(phone, isNotEmpty, reason: '''
전화번호 줄을 둘 거면 값이 있거나 $kBlank 여야 합니다. 빈 줄은 문서가 깨진 것으로 읽힙니다.''');
      }
    });

    test('문서가 근거 조문을 스스로 댄다', () {
      expect(_flat(_privacy), contains('제30조제1항제6호'), reason: '''
왜 이 칸들이 있는지가 문서 안에 없으면, 다음 사람이 "군더더기" 로 보고 지웁니다.''');
    });

    test('비어 있는 칸이 있다는 것을 본문이 말한다', () {
      final source = _flat(_privacy);
      if (source.contains(kBlank)) {
        expect(source, contains('비어 있습니다'), reason: '''
$kBlank 를 적었으면 왜 비어 있고 언제 채우는지도 본문이 말해야 합니다.
표시만 있고 설명이 없으면 이용자는 문서가 미완성이라고만 읽습니다.''');
      }
    });
  });

  group('위치기반서비스 이용약관 — 신고 대상이 아님을 문서가 말한다', () {
    test('서비스명·제공자·이메일 칸이 있다', () {
      _expectFields(
        _location,
        const ['서비스명', '제공자', '이메일'],
        why: '법이 강제하는 칸은 아니지만, 이용자가 "누가 만들었고 어디로 연락하나" 를 '
            '물을 자리입니다. 이것까지 없으면 약관을 둘 이유가 없습니다.',
      );
    });

    test('왜 신고 대상이 아닌지를 문서가 스스로 말한다', () {
      final source = _flat(_location);
      expect(source, contains('제9조제1항'), reason: '''
이 약관이 법정 기재사항을 안 갖춘 이유가 문서 안에 없으면, 다음 사람이 "부실하다" 고 읽고
없는 의무(제19조의 상호·주소·전화번호)를 다시 만들어 넣습니다. 실제로 한 번 그렇게 갔다 왔습니다.''');
      expect(source, contains('개인위치정보를 대상으로 하지 아니하는'), reason: '''
근거가 되는 문구를 그대로 인용해 두어야 다음 사람이 조문을 다시 찾지 않습니다.''');
    });

    test('언제 이 판단이 뒤집히는지도 말한다', () {
      // 산책 경로를 서버에 올리기 시작하면 그때는 개인위치정보다. 그 조건이 문서에
      // 적혀 있어야, 기능을 켜는 사람이 약관도 함께 봐야 한다는 것을 안다.
      expect(_flat(_location), contains('신고 의무'), reason: '''
"지금은 아니다" 만 적고 "언제부터는 맞다" 를 안 적으면, 나중에 산책 경로 업로드를 켜는
사람이 이 문서를 볼 이유를 못 찾습니다.''');
    });
  });

  group('빈 칸과 가짜 값', () {
    test('빈 칸 표시는 두 문서가 같은 한 가지만 쓴다', () {
      // 표시가 여럿이면 출시 전에 grep 한 번으로 못 찾는다.
      final both = _flat(_privacy) + ' ' + _flat(_location);
      final others = RegExp(r'\((?:미정|추후|TBD|tbd|나중에)[^)]*\)')
          .allMatches(both)
          .map((m) => m.group(0)!)
          .toSet();
      expect(others, isEmpty, reason: '''
빈 칸 표시는 $kBlank 하나만 씁니다. 찾은 것: $others''');
    });

    test('견본 값이 문서에 들어와 있지 않다', () {
      final both = _read(_privacy) + _read(_location);
      for (final sample in const ['홍길동', '000-0000-0000', '02-0000-0000', 'example.com']) {
        expect(both, isNot(contains(sample)), reason: '''
견본 값 "$sample" 이 문서에 있습니다. 연락이 안 닿는 정보가 적힌 법정 문서는
아예 없는 것보다 나쁩니다 — 값이 없으면 $kBlank 로 두세요.''');
      }
    });
  });
}
