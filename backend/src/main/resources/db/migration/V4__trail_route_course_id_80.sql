-- V4__trail_route_course_id_80.sql — 추천 코스 번호가 들어가게 칸을 넓힌다 (이슈 #782)
--
-- trail_route.course_id 는 #291 에서 두루누비 코스 번호(T_CRS_MNG0000005118, 19자)를
-- 담으려고 varchar(32) 로 정했다. #725 가 같은 표에 추천 코스를 loop:{contentId}:{lengthM}
-- 으로 넣으면서 두루누비 장소의 코스는 loop:trail:T_CRS_MNG0000005118:2000(35자),
-- 놀이터 장소의 코스는 loop:playground:7d10ab19d06a:2000(33자)이 됐다. 32자를 넘으면
-- 저장이 MySQL 1406 으로 죽고 응답은 500 이며, 실패마다 ORS 를 세 번 부르고 아무것도 안 남긴다.
--
-- 왜 80 인가
--
--   이 저장소에서 장소 번호를 담는 칸은 전부 64자다(pet_place_detail.content_id ·
--   post.content_id · walk.place_content_id). 64자 번호로 만들 수 있는 가장 긴 코스 번호가
--   loop: 5 + 64 + : 1 + 10000 5 = 75자라 그것을 덮는다. 엔티티의
--   TrailRoute.COURSE_ID_LENGTH 와 같아야 하고, TrailRouteCourseIdWidthTest 가 그 계산을 잠근다.
--
-- 표를 복사한다
--
--   utf8mb4 에서 32자는 128바이트, 80자는 320바이트라 길이 머리가 1바이트에서 2바이트로
--   바뀐다. MySQL 은 그 확장을 제자리에서 못 하고 표를 복사한다(그동안 쓰기가 기다린다).
--   PK 칸이라서도 그렇다. 표는 코스 몇백 줄이라 순간이다.
--
-- 옛 코드와도 맞는다
--
--   넓히기만 하므로 이 파일을 먼저 돌리고 옛 코드가 떠 있어도 아무 일이 없다. 이미 저장된
--   두루누비 선과 추천 코스는 번호가 그대로라 그대로 읽힌다.
--
-- 되돌리기
--
--   ALTER TABLE trail_route MODIFY course_id varchar(32) NOT NULL;
--   — 32자를 넘는 번호가 이미 저장돼 있으면 MySQL 이 1265/1406 으로 거절한다. 그 줄들을
--     먼저 지워야 한다(추천 코스는 다음 요청이 다시 받는다 — ORS 예산을 쓴다).
